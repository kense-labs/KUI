/// Computed 2D tile bounds inside a squarified treemap.
#[derive(Clone, Debug, PartialEq)]
pub struct TreemapRect {
    pub id: SharedString,
    pub x: f32,
    pub y: f32,
    pub w: f32,
    pub h: f32,
}

/// Compute an order-preserving squarified treemap layout over `(0, 0, width, height)`.
pub fn compute_squarified_treemap(
    items: &[(SharedString, f32)],
    width: f32,
    height: f32,
) -> Vec<TreemapRect> {
    let positive: Vec<(SharedString, f32)> = items
        .iter()
        .filter(|(_, v)| *v > 0.0)
        .map(|(id, v)| (id.clone(), *v))
        .collect();
    if positive.is_empty() || width <= 1.0 || height <= 1.0 {
        return Vec::new();
    }

    let total_val: f32 = positive.iter().map(|(_, v)| *v).sum();
    let total_area = width * height;
    let scaled: Vec<(SharedString, f32)> = positive
        .into_iter()
        .map(|(id, v)| (id, (v / total_val) * total_area))
        .collect();

    let mut out = Vec::with_capacity(scaled.len());
    squarify_slice(&scaled, 0.0, 0.0, width, height, &mut out);
    out
}

fn squarify_slice(
    items: &[(SharedString, f32)],
    mut x: f32,
    mut y: f32,
    mut w: f32,
    mut h: f32,
    out: &mut Vec<TreemapRect>,
) {
    let mut idx = 0usize;
    while idx < items.len() {
        if w <= 0.5 || h <= 0.5 {
            for (id, _) in &items[idx..] {
                out.push(TreemapRect {
                    id: id.clone(),
                    x,
                    y,
                    w: w.max(0.0),
                    h: h.max(0.0),
                });
            }
            break;
        }
        let short_side = w.min(h).max(1.0);
        let mut row_end = idx + 1;
        let mut row_sum = items[idx].1;
        let mut best_worst = worst_aspect(&items[idx..row_end], row_sum, short_side);

        while row_end < items.len() {
            let candidate_sum = row_sum + items[row_end].1;
            let candidate_worst = worst_aspect(&items[idx..=row_end], candidate_sum, short_side);
            if candidate_worst <= best_worst {
                row_sum = candidate_sum;
                best_worst = candidate_worst;
                row_end += 1;
            } else {
                break;
            }
        }

        // Lay out `items[idx..row_end]` along the shorter side
        if w >= h {
            // Vertical strip on the left of width `strip_w = row_sum / h`
            let strip_w = (row_sum / h.max(1.0)).min(w);
            let mut cur_y = y;
            for (k, (id, area)) in items[idx..row_end].iter().enumerate() {
                let tile_h = if k + 1 == row_end - idx {
                    (y + h - cur_y).max(0.0)
                } else {
                    (area / strip_w.max(1.0)).min((y + h - cur_y).max(0.0))
                };
                out.push(TreemapRect {
                    id: id.clone(),
                    x,
                    y: cur_y,
                    w: strip_w,
                    h: tile_h,
                });
                cur_y += tile_h;
            }
            x += strip_w;
            w = (w - strip_w).max(0.0);
        } else {
            // Horizontal strip on the top of height `strip_h = row_sum / w`
            let strip_h = (row_sum / w.max(1.0)).min(h);
            let mut cur_x = x;
            for (k, (id, area)) in items[idx..row_end].iter().enumerate() {
                let tile_w = if k + 1 == row_end - idx {
                    (x + w - cur_x).max(0.0)
                } else {
                    (area / strip_h.max(1.0)).min((x + w - cur_x).max(0.0))
                };
                out.push(TreemapRect {
                    id: id.clone(),
                    x: cur_x,
                    y,
                    w: tile_w,
                    h: strip_h,
                });
                cur_x += tile_w;
            }
            y += strip_h;
            h = (h - strip_h).max(0.0);
        }

        idx = row_end;
    }
}

fn worst_aspect(row: &[(SharedString, f32)], sum: f32, side: f32) -> f32 {
    if row.is_empty() || sum <= 1e-4 || side <= 1e-4 {
        return f32::MAX;
    }
    let s2 = sum * sum;
    let side2 = side * side;
    let mut worst = 0.0f32;
    for &(_, a) in row {
        let a = a.max(1e-4);
        let r1 = (side2 * a) / s2;
        let r2 = s2 / (side2 * a);
        worst = worst.max(r1.max(r2));
    }
    worst
}

struct TileBoundsAnim {
    tx: f32,
    ty: f32,
    tw: f32,
    th: f32,
    x: Slide,
    y: Slide,
    w: Slide,
    h: Slide,
}

#[derive(IntoElement)]
struct GlidingTreemapTile {
    id: ElementId,
    rect: TreemapRect,
    kind: ContextBlockKind,
    fate: Option<BlockFate>,
    label: SharedString,
    tokens_str: SharedString,
    pinned: bool,
    dimmed: bool,
    bg: Hsla,
    edge: Hsla,
    ink: Hsla,
    hatch: Hsla,
    #[allow(clippy::type_complexity)]
    on_hover: Option<Box<dyn Fn(&bool, &mut Window, &mut App) + 'static>>,
    #[allow(clippy::type_complexity)]
    on_click: Option<Box<dyn Fn(&ClickEvent, &mut Window, &mut App) + 'static>>,
}

impl RenderOnce for GlidingTreemapTile {
    fn render(self, w: &mut Window, cx: &mut App) -> impl IntoElement {
        let tx = self.rect.x + TILE_GAP * 0.5;
        let ty = self.rect.y + TILE_GAP * 0.5;
        let tw = (self.rect.w - TILE_GAP).max(0.0);
        let th = (self.rect.h - TILE_GAP).max(0.0);

        let st = w.use_keyed_state(pro_eid(&self.id, "tbounds"), cx, |_, _| TileBoundsAnim {
            tx,
            ty,
            tw,
            th,
            x: Slide::new(tx),
            y: Slide::new(ty),
            w: Slide::new(tw),
            h: Slide::new(th),
        });

        let (cx_x, cy_y, cw_w, ch_h) = st.update(cx, |s, cx| {
            if (s.tx - tx).abs() > 0.4
                || (s.ty - ty).abs() > 0.4
                || (s.tw - tw).abs() > 0.4
                || (s.th - th).abs() > 0.4
            {
                s.tx = tx;
                s.ty = ty;
                s.tw = tw;
                s.th = th;
                s.x.duration(tx, 0.38, cx);
                s.y.duration(ty, 0.38, cx);
                s.w.duration(tw, 0.38, cx);
                s.h.duration(th, 0.38, cx);
            }
            (
                s.x.get(w, cx),
                s.y.get(w, cx),
                s.w.get(w, cx).max(0.0),
                s.h.get(w, cx).max(0.0),
            )
        });

        let radius = 6.0f32.min(cw_w * 0.25).min(ch_h * 0.25).max(2.0);
        let show_name = cw_w >= 62.0 && ch_h >= 26.0;
        let show_tokens = cw_w >= 62.0 && ch_h >= 44.0;
        let is_free = self.kind == ContextBlockKind::Free;
        let is_summarized_before = self.fate == Some(BlockFate::Summarized);
        let is_dropped_before = self.fate == Some(BlockFate::Dropped);

        let edge_col = if self.pinned { self.ink } else { self.edge };
        let hatch_col = self.hatch;

        let free_decor = if is_free || is_summarized_before {
            let dash_c = if is_summarized_before {
                self.ink.opacity(0.55)
            } else {
                edge_col
            };
            let draw_hatch = is_free;
            Some(
                canvas(
                    |_, _, _| (),
                    move |bounds, _, window, _| {
                        let bw = f32::from(bounds.size.width);
                        let bh = f32::from(bounds.size.height);
                        if bw <= 6.0 || bh <= 6.0 {
                            return;
                        }
                        if draw_hatch {
                            let mut hb = PathBuilder::stroke(px(1.0));
                            let mut d = -bh;
                            let mut any = false;
                            while d < bw + bh {
                                let x0 = d.clamp(0.0, bw);
                                let y0 = (d - x0).clamp(0.0, bh);
                                let x1 = (d - bh).clamp(0.0, bw);
                                let y1 = (d - x1).clamp(0.0, bh);
                                hb.move_to(point(bounds.left() + px(x0), bounds.top() + px(y0)));
                                hb.line_to(point(bounds.left() + px(x1), bounds.top() + px(y1)));
                                any = true;
                                d += 10.0;
                            }
                            if any && let Ok(path) = hb.build() {
                                window.paint_path(path, hatch_col);
                            }
                        }

                        // Dashed inner rectangle (`inset 2px`)
                        let inset = 2.0f32;
                        let rx0 = f32::from(bounds.left()) + inset;
                        let ry0 = f32::from(bounds.top()) + inset;
                        let rx1 = f32::from(bounds.right()) - inset;
                        let ry1 = f32::from(bounds.bottom()) - inset;
                        if rx1 <= rx0 + 4.0 || ry1 <= ry0 + 4.0 {
                            return;
                        }
                        let mut db = PathBuilder::stroke(px(1.2));
                        let step = 5.0f32;
                        let dash = 3.0f32;
                        let mut x = rx0;
                        while x < rx1 {
                            let xe = (x + dash).min(rx1);
                            db.move_to(point(px(x), px(ry0)));
                            db.line_to(point(px(xe), px(ry0)));
                            db.move_to(point(px(x), px(ry1)));
                            db.line_to(point(px(xe), px(ry1)));
                            x += step;
                        }
                        let mut y = ry0;
                        while y < ry1 {
                            let ye = (y + dash).min(ry1);
                            db.move_to(point(px(rx0), px(y)));
                            db.line_to(point(px(rx0), px(ye)));
                            db.move_to(point(px(rx1), px(y)));
                            db.line_to(point(px(rx1), px(ye)));
                            y += step;
                        }
                        if let Ok(path) = db.build() {
                            window.paint_path(path, dash_c);
                        }
                    },
                )
                .absolute()
                .inset_0(),
            )
        } else {
            None
        };

        let mut tile = div()
            .id(self.id)
            .role(Role::ListBoxOption)
            .aria_label(format!("{}: {}", self.label, self.tokens_str))
            .aria_selected(self.pinned)
            .absolute()
            .left(px(cx_x))
            .top(px(cy_y))
            .w(px(cw_w))
            .h(px(ch_h))
            .rounded(px(radius))
            .bg(self.bg)
            .when(!is_free && !is_summarized_before, |d| {
                d.border_1().border_color(edge_col)
            })
            .opacity(if is_dropped_before {
                0.42
            } else if self.dimmed {
                0.55
            } else {
                1.0
            })
            .when(!is_free, |d| d.cursor_pointer())
            .overflow_hidden();

        if let Some(hov) = self.on_hover {
            tile = tile.on_hover(move |inside, w, cx| hov(inside, w, cx));
        }
        if let Some(clk) = self.on_click {
            tile = tile.on_click(move |ev, w, cx| clk(ev, w, cx));
        }
        if let Some(decor) = free_decor {
            tile = tile.child(decor);
        }

        if show_name {
            tile = tile.child(
                div()
                    .relative()
                    .px(px(9.0))
                    .pt(px(7.0))
                    .flex()
                    .flex_col()
                    .gap(px(1.0))
                    .child(
                        div()
                            .truncate()
                            .text_size(px(12.0))
                            .font_weight(FontWeight::MEDIUM)
                            .text_color(self.ink)
                            .when(is_dropped_before, |d| d.line_through())
                            .child(self.label),
                    )
                    .when(show_tokens, |col| {
                        col.child(
                            div()
                                .truncate()
                                .text_size(px(11.5))
                                .text_color(self.ink.opacity(0.75))
                                .child(self.tokens_str),
                        )
                    }),
            );
        }

        tile
    }
}

