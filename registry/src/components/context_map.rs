const TILE_GAP: f32 = 3.0;

/// Events emitted by [`ContextMap`].
#[derive(Clone, Debug, PartialEq)]
pub enum ContextMapEvent {
    /// User pinned or cleared a treemap tile (`None` when free space or unpinned).
    TileSelected(Option<ContextBlock>),
    /// User switched the inspected agent profile from the header dropdown.
    AgentChanged(SharedString),
    /// User toggled between `Before` and `After` compaction maps.
    ViewChanged(CompactionView),
    /// User appended a new context turn/result block.
    TurnAdded(ContextBlock),
    /// Context blocks were compacted into a summary tile.
    Compacted {
        before_tokens: u64,
        after_tokens: u64,
        summarized_count: usize,
    },
    /// Map state was reset to its initial uncompacted blocks.
    Reset,
}

/// Semantic kind of a [`ContextBlock`] tile inside [`ContextMap`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum ContextBlockKind {
    /// System prompt instructions (neutral slate).
    #[default]
    System,
    /// Tool and MCP schema definitions (cyan).
    Tools,
    /// Persistent workspace or user memory notes (purple).
    Memory,
    /// Individual source file read into context (blue).
    File,
    /// Multi-turn conversation history (violet).
    Chat,
    /// Tool execution output or test log (amber/orange).
    Result,
    /// Condensed summary generated by compaction (emerald green).
    Summary,
    /// Remaining available window capacity (diagonal hatch + dashed border).
    Free,
}

impl ContextBlockKind {
    fn colors(self, p: &ProPalette) -> (Hsla, Hsla, Hsla) {
        match self {
            Self::System => (
                if p.dark {
                    hsla(0., 0., 1., 0.07)
                } else {
                    hsla(0., 0., 0., 0.05)
                },
                if p.dark {
                    hsla(0., 0., 1., 0.15)
                } else {
                    hsla(0., 0., 0., 0.12)
                },
                p.text,
            ),
            Self::Tools => (
                p.cyan.opacity(if p.dark { 0.16 } else { 0.10 }),
                p.cyan.opacity(0.36),
                if p.dark { p.cyan } else { rgb(0x08658c).into() },
            ),
            Self::Memory => (
                p.purple.opacity(if p.dark { 0.18 } else { 0.11 }),
                p.purple.opacity(0.38),
                p.purple,
            ),
            Self::File => (p.accent_soft, p.blue.opacity(0.34), p.accent_info),
            Self::Chat => (
                p.pink.opacity(if p.dark { 0.15 } else { 0.09 }),
                p.pink.opacity(0.34),
                p.pink,
            ),
            Self::Result => (
                p.orange.opacity(if p.dark { 0.17 } else { 0.13 }),
                p.orange.opacity(0.40),
                p.amber_ink,
            ),
            Self::Summary => (p.green_soft, p.green.opacity(0.40), p.green_ink),
            Self::Free => (transparent_black(), p.line_strong, p.muted),
        }
    }

    fn label(self, cx: &App) -> &'static str {
        match self {
            Self::System => tr(cx, "System", "系统提示"),
            Self::Tools => tr(cx, "Tools", "工具定义"),
            Self::Memory => tr(cx, "Memory", "记忆库"),
            Self::File => tr(cx, "File", "源码文件"),
            Self::Chat => tr(cx, "Chat", "对话轮次"),
            Self::Result => tr(cx, "Tool result", "执行结果"),
            Self::Summary => tr(cx, "Summary", "压缩摘要"),
            Self::Free => tr(cx, "Free space", "剩余可用"),
        }
    }
}

/// Which side of a compaction snapshot [`ContextMap`] displays.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum CompactionView {
    /// Pre-compaction layout highlighting blocks that were summarized or dropped.
    Before,
    /// Active post-compaction layout with the condensed summary tile.
    #[default]
    After,
}

/// Compaction fate tag shown when inspecting [`CompactionView::Before`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BlockFate {
    Kept,
    Summarized,
    Dropped,
    Summary,
}

/// One context segment rendered as a proportional 2D tile in [`ContextMap`].
#[derive(Clone, Debug, PartialEq)]
pub struct ContextBlock {
    /// Stable block id so tiles glide smoothly across layout changes.
    pub id: SharedString,
    /// Tile heading (`"System prompt"`, `"checkout.spec.ts"`).
    pub label: SharedString,
    /// Optional Chinese tile heading.
    pub label_zh: Option<SharedString>,
    /// Tile category tint.
    pub kind: ContextBlockKind,
    /// Token count occupied by this block.
    pub tokens: u64,
    /// Optional provenance or timing note (`"Read at 0:09"`).
    pub detail: Option<SharedString>,
    /// Optional Chinese provenance note.
    pub detail_zh: Option<SharedString>,
    /// Optional app logo key (`"github"`, `"linear"`, `"stripe"`).
    pub app: Option<SharedString>,
    /// Optional child item names shown inside the hover/pinned inspector popover.
    pub items: Vec<SharedString>,
}

impl ContextBlock {
    /// Create a [`ContextBlock`] with `id`, `label`, `kind`, and `tokens`.
    pub fn new(
        id: impl Into<SharedString>,
        label: impl Into<SharedString>,
        kind: ContextBlockKind,
        tokens: u64,
    ) -> Self {
        Self {
            id: id.into(),
            label: label.into(),
            label_zh: None,
            kind,
            tokens,
            detail: None,
            detail_zh: None,
            app: None,
            items: Vec::new(),
        }
    }

    /// Set localized Chinese label.
    pub fn with_label_zh(mut self, label_zh: impl Into<SharedString>) -> Self {
        self.label_zh = Some(label_zh.into());
        self
    }

    /// Attach a detail subtitle (`"Read at 0:09"`).
    pub fn with_detail(
        mut self,
        detail: impl Into<SharedString>,
        detail_zh: impl Into<SharedString>,
    ) -> Self {
        self.detail = Some(detail.into());
        self.detail_zh = Some(detail_zh.into());
        self
    }

    /// Set leading app logo key.
    pub fn with_app(mut self, app: impl Into<SharedString>) -> Self {
        self.app = Some(app.into());
        self
    }

    /// Attach sub-items listed inside the tile inspector popover.
    pub fn with_items(mut self, items: Vec<SharedString>) -> Self {
        self.items = items;
        self
    }

    fn display_label<'a>(&'a self, cx: &App) -> &'a str {
        match &self.label_zh {
            Some(zh) => tr(cx, self.label.as_ref(), zh.as_ref()),
            None => self.label.as_ref(),
        }
    }

    fn display_detail<'a>(&'a self, cx: &App) -> Option<&'a str> {
        match (&self.detail, &self.detail_zh) {
            (Some(en), Some(zh)) => Some(tr(cx, en.as_ref(), zh.as_ref())),
            (Some(en), None) => Some(en.as_ref()),
            _ => None,
        }
    }
}

