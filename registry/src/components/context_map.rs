fn fmt_tok(tokens: u64) -> String {
    if tokens < 1_000 {
        tokens.to_string()
    } else {
        let k = tokens as f64 / 1_000.0;
        if (k - k.round()).abs() < 0.05 {
            format!("{}K", k.round() as u64)
        } else {
            format!("{k:.1}K")
        }
    }
}

