//! Living squarified treemap of an agent's context window with gliding tiles and compaction comparison.
//!
//! Renders `System prompt`, `Tools`, `Memory`, individual `Files`, `Chat`, `Tool results`,
//! `Summary`, and dashed `Free space` as proportional 2D squarified treemap tiles whose `(x, y, w, h)`
//! bounds glide smoothly via [`Slide`] springs as turns are added, agents are switched, or `"Compact"`
//! condenses historical chat and tool outputs into a summary tile with `Before | After` inspection.

