    pub fn with_title_zh(mut self, title_zh: impl Into<SharedString>) -> Self {
        self.title_zh = Some(title_zh.into());
        self
    }

    /// Supply explicit [`ContextBlock`] tiles and token `limit`.
    pub fn with_blocks(mut self, blocks: Vec<ContextBlock>, limit: u64) -> Self {
        self.initial_blocks = blocks.clone();
        self.blocks = blocks;
        self.limit = limit.max(1_000);
        self.compaction = None;
        self
    }

    /// Configure switchable [`ContextAgentProfile`] presets.
    pub fn with_profiles(mut self, profiles: Vec<ContextAgentProfile>) -> Self {
        if let Some(first) = profiles.first().cloned() {
            self.initial_blocks = first.blocks.clone();
            self.blocks = first.blocks;
            self.limit = first.limit;
            self.active_profile_idx = 0;
        }
        self.profiles = profiles;
        self.compaction = None;
        self
    }

