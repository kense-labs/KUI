#[cfg(test)]
mod tests {
    use super::{CompactionView, ContextMap, compute_squarified_treemap};
    use gpui::{AppContext as _, SharedString, TestAppContext};

    #[test]
    fn squarified_treemap_conserves_total_area_and_stays_in_bounds() {
        let items = vec![
            (SharedString::from("sys"), 6_400.0),
            (SharedString::from("tools"), 14_800.0),
            (SharedString::from("chat"), 38_000.0),
            (SharedString::from("free"), 80_000.0),
        ];
        let rects = compute_squarified_treemap(&items, 600.0, 260.0);
        assert_eq!(rects.len(), 4);

        let area_sum: f32 = rects.iter().map(|r| r.w * r.h).sum();
        assert!(
            (area_sum - 600.0 * 260.0).abs() < 2.0,
            "expected conserved area, got {area_sum}"
        );
        for r in &rects {
            assert!(r.x >= -0.01 && r.y >= -0.01);
            assert!(r.x + r.w <= 600.1 && r.y + r.h <= 260.1);
            assert!(r.w > 0.0 && r.h > 0.0);
        }
    }

    #[gpui::test]
    fn compact_condenses_turns_into_summary_and_supports_before_after_view(
        cx: &mut TestAppContext,
    ) {
        cx.update(crate::init);
        let view = cx.new(|cx| ContextMap::new("test-context-map", cx));

        view.update(cx, |v, cx| {
            let initial_used = v.displayed_used_tokens();
            assert_eq!(initial_used, 137_200);

            v.add_turn(cx);
            let grown_used = v.displayed_used_tokens();
            assert!(grown_used > initial_used);

            assert!(v.compact_context(cx));
            let after_used = v.displayed_used_tokens();
            assert!(
                after_used < grown_used,
                "compaction shrinks used context and expands free space"
            );
            assert_eq!(v.view(), CompactionView::After);
        });
    }
}
