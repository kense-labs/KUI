#[cfg(test)]
mod tests {
    use super::{TraceSpan, TraceSpanKind, TraceSpanStatus, compute_trace_summary};
    use gpui::SharedString;
    use std::collections::HashSet;

    #[test]
    fn trace_summary_marks_slowest_call_and_embeds_folded_child_marks() {
        let root = TraceSpan::new("run", "Orchestrator", TraceSpanKind::Agent, 0)
            .with_status(TraceSpanStatus::Running)
            .with_children(vec![
                TraceSpan::new("fast", "Fast LLM", TraceSpanKind::Llm, 200)
                    .with_end_ms(1_400)
                    .with_tokens(1_000, 200)
                    .with_cost(0.012),
                TraceSpan::new("sub", "Sub-agent", TraceSpanKind::SubAgent, 1_500)
                    .with_end_ms(6_800)
                    .with_children(vec![
                        TraceSpan::new("slow", "Deep synthesis", TraceSpanKind::Llm, 1_600)
                            .with_end_ms(6_200)
                            .with_tokens(4_000, 900)
                            .with_cost(0.075),
                        TraceSpan::new("err", "webhook", TraceSpanKind::Tool, 6_250)
                            .with_end_ms(6_750)
                            .with_error("504 timeout"),
                    ]),
            ]);

        let mut folded = HashSet::new();
        folded.insert(SharedString::from("sub"));
        let summary = compute_trace_summary(&root, 7_500, 10_000, true, &folded);

        assert_eq!(summary.llm_calls, 2);
        assert_eq!(summary.tool_calls, 1);
        assert_eq!(summary.error_count, 1);
        assert_eq!(summary.slowest_id.as_deref(), Some("slow"));
        assert_eq!(summary.total_tokens, 6_100);
        // Sub-agent row is folded, hiding its 2 children and retaining 2 folded mini-marks.
        assert!(summary.rows[2].folded);
        assert_eq!(summary.rows[2].folded_marks.len(), 2);
        assert!(!summary.rows[3].visible);
    }
}
