#[derive(Clone, Copy, Debug)]
struct FoldedMark {
    start_ms: u64,
    dur_ms: u64,
    kind: TraceSpanKind,
    failed: bool,
}

#[derive(Clone, Debug)]
struct FlatSpanRow {
    id: SharedString,
    parent_id: Option<SharedString>,
    name: SharedString,
    kind: TraceSpanKind,
    status: TraceSpanStatus,
    detail: Option<SharedString>,
    model: Option<SharedString>,
    artwork_key: Option<SharedString>,
    level: usize,
    has_children: bool,
    descendant_calls: usize,
    folded: bool,
    visible: bool,
    start_ms: u64,
    end_ms: u64,
    duration_ms: u64,
    tokens_in: u64,
    tokens_out: u64,
    cost: f64,
    folded_marks: Vec<FoldedMark>,
    input: Option<SharedString>,
    output: Option<SharedString>,
    error: Option<SharedString>,
}

#[derive(Clone, Debug)]
struct TraceSummary {
    rows: Vec<FlatSpanRow>,
    total_duration_ms: u64,
    total_cost: f64,
    total_tokens: u64,
    llm_calls: usize,
    tool_calls: usize,
    error_count: usize,
    slowest_id: Option<SharedString>,
    axis_range_ms: u64,
    run_status: TraceSpanStatus,
}

fn infer_span_artwork(span: &TraceSpan) -> Option<SharedString> {
    if let Some(ic) = &span.icon {
        return Some(ic.clone());
    }
    if let Some(m) = &span.model {
        let lower = m.to_ascii_lowercase();
        if lower.contains("claude") || lower.contains("opus") || lower.contains("sonnet") {
            return Some("claude".into());
        }
        if lower.contains("gemini") {
            return Some("gemini".into());
        }
        if lower.contains("gpt")
            || lower.contains("o1")
            || lower.contains("o3")
            || lower.contains("openai")
        {
            return Some("openai".into());
        }
    }
    let nl = span.name.to_ascii_lowercase();
    let dl = span
        .detail
        .as_ref()
        .map(|d| d.to_ascii_lowercase())
        .unwrap_or_default();
    if nl.contains("stripe") || dl == "stripe" {
        return Some("stripe".into());
    }
    if nl.contains("github") || dl == "github" {
        return Some("github".into());
    }
    if nl.contains("slack") || dl == "slack" {
        return Some("slack".into());
    }
    if nl.contains("notion") || dl == "notion" {
        return Some("notion".into());
    }
    if matches!(span.kind, TraceSpanKind::Agent | TraceSpanKind::SubAgent) {
        for child in &span.children {
            if child.kind == TraceSpanKind::Llm
                && let Some(art) = infer_span_artwork(child)
            {
                return Some(art);
            }
        }
    }
    None
}

fn infer_trace_tool_icon(name: &str, detail: Option<&str>) -> ProIcon {
    let nl = name.to_ascii_lowercase();
    let dl = detail.map(str::to_ascii_lowercase).unwrap_or_default();
    if nl.contains("db")
        || nl.contains("sql")
        || nl.contains("postgres")
        || nl.contains("usage")
        || dl.contains("postgres")
        || dl.contains("sql")
    {
        ProIcon::Database
    } else if nl.contains("search") || nl.contains("find") || nl.contains("query") {
        ProIcon::Search
    } else if nl.contains("fetch")
        || nl.contains("http")
        || nl.contains("web")
        || nl.contains("url")
        || nl.contains("review")
        || nl.contains("page")
    {
        ProIcon::Globe
    } else if nl.contains("verify")
        || nl.contains("check")
        || nl.contains("valid")
        || nl.contains("cit")
    {
        ProIcon::Check
    } else if nl.contains("read") || nl.contains("file") || nl.contains("doc") {
        ProIcon::PageDoc
    } else if nl.contains("hook") || nl.contains("link") {
        ProIcon::Link
    } else {
        ProIcon::Terminal
    }
}

fn render_trace_running_spinner(elapsed_secs: f32, reduced: bool, color: Hsla) -> AnyElement {
    let angle = if reduced {
        -std::f32::consts::FRAC_PI_2
    } else {
        (elapsed_secs / 0.85).fract() * std::f32::consts::TAU
    };
    canvas(
        |_, _, _| (),
        move |bounds, _, window, _| {
            let center = bounds.center();
            let r = (f32::from(bounds.size.width).min(f32::from(bounds.size.height)) - 2.0) * 0.5;
            if r <= 1.0 {
                return;
            }
            let steps = 28usize;
            let mut track = PathBuilder::stroke(px(1.65));
            for i in 0..=steps {
                let a = (i as f32 / steps as f32) * std::f32::consts::TAU;
                let pt = center + point(px(r * a.cos()), px(r * a.sin()));
                if i == 0 {
                    track.move_to(pt);
                } else {
                    track.line_to(pt);
                }
            }
            if let Ok(path) = track.build() {
                window.paint_path(path, color.opacity(0.22));
            }
            let arc_steps = 20usize;
            let sweep = std::f32::consts::TAU * 0.70;
            let mut arc = PathBuilder::stroke(px(1.65));
            for i in 0..=arc_steps {
                let a = angle + (i as f32 / arc_steps as f32) * sweep;
                let pt = center + point(px(r * a.cos()), px(r * a.sin()));
                if i == 0 {
                    arc.move_to(pt);
                } else {
                    arc.line_to(pt);
                }
            }
            if let Ok(path) = arc.build() {
                window.paint_path(path, color);
            }
        },
    )
    .size(px(12.5))
    .flex_none()
    .into_any_element()
}

fn nice_time_axis_ms(max_ms: u64, min_range_ms: u64) -> u64 {
    let target = max_ms.max(min_range_ms).max(1_000);
    let steps: [u64; 14] = [
        2_000, 4_000, 5_000, 8_000, 10_000, 12_000, 15_000, 20_000, 30_000, 45_000, 60_000, 90_000,
        120_000, 300_000,
    ];
    for s in steps {
        if s >= (target as f64 * 1.04) as u64 {
            return s;
        }
    }
    target.div_ceil(30_000) * 30_000
}

fn format_span_ms(ms: u64) -> String {
    if ms < 1_000 {
        format!("{ms}ms")
    } else if ms < 60_000 {
        format!("{:.1}s", ms as f64 / 1_000.0)
    } else {
        format!("{}m {:02}s", ms / 60_000, (ms % 60_000) / 1_000)
    }
}

fn format_span_usd(cost: f64) -> String {
    if !cost.is_finite() || cost.abs() < 1e-6 {
        "$0".to_string()
    } else if cost < 0.01 {
        format!("${cost:.4}")
    } else if cost < 1.0 {
        let s = format!("{cost:.3}");
        format!("${}", s.trim_end_matches('0').trim_end_matches('.'))
    } else {
        format!("${cost:.2}")
    }
}

fn format_span_tokens(n: u64) -> String {
    if n < 1_000 {
        format!("{n}")
    } else if n < 100_000 {
        let s = format!("{:.1}", n as f64 / 1_000.0);
        format!("{}k", s.trim_end_matches(".0"))
    } else {
        format!("{}k", (n + 500) / 1_000)
    }
}

fn compute_trace_summary(
    root: &TraceSpan,
    now_ms: u64,
    min_range_ms: u64,
    mark_slowest: bool,
    collapsed: &HashSet<SharedString>,
) -> TraceSummary {
    let mut rows: Vec<FlatSpanRow> = Vec::new();
    let mut llm_calls = 0usize;
    let mut tool_calls = 0usize;
    let mut error_count = 0usize;
    let mut has_running = false;
    let mut slowest: Option<(SharedString, u64)> = None;
    let mut max_end = 0_u64;

    #[allow(clippy::too_many_arguments)]
    fn walk(
        span: &TraceSpan,
        parent_id: Option<SharedString>,
        level: usize,
        ancestor_hidden: bool,
        now_ms: u64,
        collapsed: &HashSet<SharedString>,
        rows: &mut Vec<FlatSpanRow>,
        llm_calls: &mut usize,
        tool_calls: &mut usize,
        error_count: &mut usize,
        has_running: &mut bool,
        slowest: &mut Option<(SharedString, u64)>,
        max_end: &mut u64,
    ) -> (u64, u64, f64, u64, usize, Vec<FoldedMark>) {
        match span.kind {
            TraceSpanKind::Llm => *llm_calls += 1,
            TraceSpanKind::Tool => *tool_calls += 1,
            TraceSpanKind::Agent | TraceSpanKind::SubAgent => {}
        }
        match span.status {
            TraceSpanStatus::Running => *has_running = true,
            TraceSpanStatus::Failed => *error_count += 1,
            TraceSpanStatus::Done => {}
        }

        let folded = collapsed.contains(&span.id);
        let idx = rows.len();
        let detail = span.detail.clone().or_else(|| span.model.clone());
        let artwork_key = infer_span_artwork(span);

        rows.push(FlatSpanRow {
            id: span.id.clone(),
            parent_id,
            name: span.name.clone(),
            kind: span.kind,
            status: span.status,
            detail,
            model: span.model.clone(),
            artwork_key,
            level,
            has_children: !span.children.is_empty(),
            descendant_calls: 0,
            folded,
            visible: !ancestor_hidden,
            start_ms: span.start_ms,
            end_ms: span.end_ms.unwrap_or(now_ms).max(span.start_ms),
            duration_ms: 0,
            tokens_in: span.tokens_in,
            tokens_out: span.tokens_out,
            cost: if span.cost.is_finite() {
                span.cost
            } else {
                0.0
            },
            folded_marks: Vec::new(),
            input: span.input.clone(),
            output: span.output.clone(),
            error: span.error.clone(),
        });

        let mut sum_in = span.tokens_in;
        let mut sum_out = span.tokens_out;
        let mut sum_cost = if span.cost.is_finite() {
            span.cost
        } else {
            0.0
        };
        let mut max_child_end = span.end_ms.unwrap_or_else(|| {
            if span.status == TraceSpanStatus::Running {
                now_ms.max(span.start_ms)
            } else {
                span.start_ms
            }
        });
        let mut desc_calls = 0usize;
        let mut marks: Vec<FoldedMark> = Vec::new();

        for child in &span.children {
            let (ci, co, cc, ce, dc, child_marks) = walk(
                child,
                Some(span.id.clone()),
                level + 1,
                ancestor_hidden || folded,
                now_ms,
                collapsed,
                rows,
                llm_calls,
                tool_calls,
                error_count,
                has_running,
                slowest,
                max_end,
            );
            sum_in += ci;
            sum_out += co;
            sum_cost += cc;
            max_child_end = max_child_end.max(ce);
            desc_calls += dc + 1;
            if child.children.is_empty() {
                marks.push(FoldedMark {
                    start_ms: child.start_ms,
                    dur_ms: ce.saturating_sub(child.start_ms),
                    kind: child.kind,
                    failed: child.status == TraceSpanStatus::Failed,
                });
            } else {
                marks.extend(child_marks);
            }
        }

        let resolved_end = match span.end_ms {
            Some(explicit) => explicit.max(span.start_ms),
            None => {
                if span.status == TraceSpanStatus::Running {
                    now_ms.max(max_child_end).max(span.start_ms)
                } else {
                    max_child_end.max(span.start_ms)
                }
            }
        };
        let dur = resolved_end.saturating_sub(span.start_ms);
        *max_end = (*max_end).max(resolved_end);

        if span.status == TraceSpanStatus::Done
            && matches!(span.kind, TraceSpanKind::Llm | TraceSpanKind::Tool)
            && dur > 0
            && slowest.as_ref().is_none_or(|(_, best)| dur > *best)
        {
            *slowest = Some((span.id.clone(), dur));
        }

        rows[idx].end_ms = resolved_end;
        rows[idx].duration_ms = dur;
        rows[idx].tokens_in = sum_in;
        rows[idx].tokens_out = sum_out;
        rows[idx].cost = sum_cost;
        rows[idx].descendant_calls = desc_calls;
        rows[idx].folded_marks = marks.clone();

        (sum_in, sum_out, sum_cost, resolved_end, desc_calls, marks)
    }

    let (tot_in, tot_out, tot_cost, root_end, _, _) = walk(
        root,
        None,
        0,
        false,
        now_ms,
        collapsed,
        &mut rows,
        &mut llm_calls,
        &mut tool_calls,
        &mut error_count,
        &mut has_running,
        &mut slowest,
        &mut max_end,
    );

    let effective_end = if has_running {
        max_end.max(now_ms)
    } else {
        max_end.max(root_end)
    };
    let run_status = if root.status == TraceSpanStatus::Failed {
        TraceSpanStatus::Failed
    } else if has_running || root.status == TraceSpanStatus::Running {
        TraceSpanStatus::Running
    } else if error_count > 0 {
        TraceSpanStatus::Done
    } else {
        root.status
    };

    TraceSummary {
        rows,
        total_duration_ms: effective_end.saturating_sub(root.start_ms),
        total_cost: tot_cost,
        total_tokens: tot_in + tot_out,
        llm_calls,
        tool_calls,
        error_count,
        slowest_id: if mark_slowest {
            slowest.map(|(id, _)| id)
        } else {
            None
        },
        axis_range_ms: nice_time_axis_ms(effective_end, min_range_ms),
        run_status,
    }
}

