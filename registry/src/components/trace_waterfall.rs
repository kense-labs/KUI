/// Live hierarchical execution trace waterfall for debugging agent latency, concurrency, and spend.
pub struct TraceWaterfall {
    id: ElementId,
    title: Option<SharedString>,
    root: Option<TraceSpan>,
    now_override_ms: Option<u64>,
    base_now_ms: u64,
    min_range_ms: u64,
    mark_slowest: bool,
    collapsed: HashSet<SharedString>,
    open_id: Option<SharedString>,
    hovered_id: Option<SharedString>,
    metric_mode: SharedString,
    focused_row: usize,
    loading: bool,
    empty: bool,
    started_at: Instant,
    measured_w: Rc<Cell<f32>>,
    focus: FocusHandle,
}

impl TraceWaterfall {
    /// Create a [`TraceWaterfall`] preloaded with the live `"Launch the new pricing page"` trace.
    pub fn new(id: impl Into<ElementId>, cx: &mut Context<Self>) -> Self {
        cx.observe_global::<crate::foundation::Theme>(|_, cx| cx.notify())
            .detach();
        cx.observe_global::<crate::primitives::control::UiLanguage>(|_, cx| cx.notify())
            .detach();
        Self {
            id: id.into(),
            title: None,
            root: Some(default_trace_root(cx)),
            now_override_ms: None,
            base_now_ms: 10_400,
            min_range_ms: 12_000,
            mark_slowest: true,
            collapsed: HashSet::new(),
            open_id: None,
            hovered_id: None,
            metric_mode: SharedString::from("cost"),
            focused_row: 0,
            loading: false,
            empty: false,
            started_at: Instant::now(),
            measured_w: Rc::new(Cell::new(756.0)),
            focus: cx.focus_handle(),
        }
    }

    /// Override the bar heading (`"Trace"` by default).
    pub fn with_title(mut self, title: impl Into<SharedString>) -> Self {
        self.title = Some(title.into());
        self
    }

    /// Supply the root [`TraceSpan`] tree for the run.
    pub fn with_root(mut self, root: TraceSpan) -> Self {
        self.root = Some(root);
        self
    }

    /// Drive the timeline's `"now"` clock explicitly in milliseconds from run start.
    pub fn with_now_ms(mut self, now_ms: Option<u64>) -> Self {
        self.now_override_ms = now_ms;
        self
    }

    /// Set the minimum time-axis window in milliseconds (`12_000` default).
    pub fn with_min_range_ms(mut self, min_range_ms: u64) -> Self {
        self.min_range_ms = min_range_ms.max(1_000);
        self
    }

    /// Enable or hide the amber `SLOWEST` badge on the slowest finished LLM or tool call.
    pub fn with_mark_slowest(mut self, mark_slowest: bool) -> Self {
        self.mark_slowest = mark_slowest;
        self
    }

    /// Pre-collapse specific parent span ids.
    pub fn with_collapsed<I, S>(mut self, ids: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<SharedString>,
    {
        self.collapsed = ids.into_iter().map(Into::into).collect();
        self
    }

    /// Pre-open a specific span's inline inspector (`pro_fold`).
    pub fn with_open_id(mut self, open_id: Option<SharedString>) -> Self {
        self.open_id = open_id;
        self
    }

    /// Render skeleton bars while trace telemetry loads.
    pub fn with_loading(mut self, loading: bool) -> Self {
        self.loading = loading;
        self
    }

    /// Render the empty trace state.
    pub fn with_empty(mut self, empty: bool) -> Self {
        self.empty = empty;
        self
    }

    fn effective_now_ms(&self, reduced: bool) -> u64 {
        if let Some(explicit) = self.now_override_ms {
            return explicit;
        }
        if reduced {
            return self.base_now_ms;
        }
        // Loop smoothly across 9.8s..11.8s so the live span & "now" line breathe naturally in previews without unbounded axis drift.
        let cycle_ms = ((self.started_at.elapsed().as_secs_f32() * 420.0) % 1_800.0) as u64;
        self.base_now_ms + cycle_ms
    }

    fn toggle_open(&mut self, id: SharedString, cx: &mut Context<Self>) {
        if self.open_id.as_ref() == Some(&id) {
            self.open_id = None;
        } else {
            self.open_id = Some(id);
        }
        cx.emit(TraceWaterfallEvent::OpenChanged(self.open_id.clone()));
        cx.notify();
    }

    fn toggle_fold(&mut self, id: SharedString, cx: &mut Context<Self>) {
        if !self.collapsed.remove(&id) {
            self.collapsed.insert(id.clone());
            if let Some(root) = &self.root {
                let summary = compute_trace_summary(
                    root,
                    self.base_now_ms,
                    self.min_range_ms,
                    self.mark_slowest,
                    &self.collapsed,
                );
                if let Some(open) = &self.open_id
                    && summary.rows.iter().any(|r| &r.id == open && !r.visible)
                {
                    self.open_id = None;
                    cx.emit(TraceWaterfallEvent::OpenChanged(None));
                }
            }
        }
        let mut list: Vec<SharedString> = self.collapsed.iter().cloned().collect();
        list.sort();
        cx.emit(TraceWaterfallEvent::CollapsedChanged(list));
        cx.notify();
    }

    fn handle_key_down(&mut self, ev: &KeyDownEvent, _w: &mut Window, cx: &mut Context<Self>) {
        let Some(root) = &self.root else {
            return;
        };
        let summary = compute_trace_summary(
            root,
            self.base_now_ms,
            self.min_range_ms,
            self.mark_slowest,
            &self.collapsed,
        );
        let vis: Vec<&FlatSpanRow> = summary.rows.iter().filter(|r| r.visible).collect();
        if vis.is_empty() {
            return;
        }
        let cur = self.focused_row.min(vis.len() - 1);
        match ev.keystroke.key.as_str() {
            "down" => {
                self.focused_row = (cur + 1).min(vis.len() - 1);
                cx.notify();
            }
            "up" => {
                self.focused_row = cur.saturating_sub(1);
                cx.notify();
            }
            "home" => {
                self.focused_row = 0;
                cx.notify();
            }
            "end" => {
                self.focused_row = vis.len() - 1;
                cx.notify();
            }
            "right" => {
                let row = vis[cur];
                if row.has_children && row.folded {
                    self.toggle_fold(row.id.clone(), cx);
                } else if row.has_children && cur + 1 < vis.len() {
                    self.focused_row = cur + 1;
                    cx.notify();
                }
            }
            "left" => {
                let row = vis[cur];
                if row.has_children && !row.folded {
                    self.toggle_fold(row.id.clone(), cx);
                } else if let Some(pid) = &row.parent_id
                    && let Some(pos) = vis.iter().position(|r| &r.id == pid)
                {
                    self.focused_row = pos;
                    cx.notify();
                }
            }
            "enter" | "space" => {
                let id = vis[cur].id.clone();
                self.toggle_open(id, cx);
            }
            "escape" if self.open_id.take().is_some() => {
                cx.emit(TraceWaterfallEvent::OpenChanged(None));
                cx.notify();
            }
            _ => {}
        }
    }
}

