/// Category of a [`TraceSpan`] determining bar tint and inspector metadata.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TraceSpanKind {
    /// Root orchestrator span (neutral slate bar).
    Agent,
    /// Delegated sub-agent span (neutral slate bar).
    SubAgent,
    /// Model inference call (violet bar).
    #[default]
    Llm,
    /// External tool or API call (cyan/teal bar).
    Tool,
}

impl TraceSpanKind {
    fn label(self, cx: &App) -> &'static str {
        match self {
            Self::Agent => tr(cx, "Agent run", "主智能体"),
            Self::SubAgent => tr(cx, "Sub-agent", "子智能体"),
            Self::Llm => tr(cx, "LLM call", "模型调用"),
            Self::Tool => tr(cx, "Tool call", "工具调用"),
        }
    }
}

/// Execution state of a [`TraceSpan`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TraceSpanStatus {
    /// Actively executing and growing toward the live `now` cursor.
    Running,
    /// Completed at `end_ms`.
    #[default]
    Done,
    /// Terminated with an error.
    Failed,
}

impl TraceSpanStatus {
    fn label(self, cx: &App) -> &'static str {
        match self {
            Self::Running => tr(cx, "Running", "运行中"),
            Self::Done => tr(cx, "Done", "已完成"),
            Self::Failed => tr(cx, "Failed", "失败"),
        }
    }
}

/// Hierarchical execution span in [`TraceWaterfall`].
#[derive(Clone, Debug, PartialEq)]
pub struct TraceSpan {
    /// Unique span identifier.
    pub id: SharedString,
    /// Span title (agent, prompt step, or tool name).
    pub name: SharedString,
    /// Span category (`Agent`, `SubAgent`, `Llm`, or `Tool`).
    pub kind: TraceSpanKind,
    /// Execution status (`Running`, `Done`, or `Failed`).
    pub status: TraceSpanStatus,
    /// Start offset in milliseconds from the beginning of the run.
    pub start_ms: u64,
    /// End offset in milliseconds from run start (`None` while running).
    pub end_ms: Option<u64>,
    /// Optional model identifier (`"Claude Opus 4.6"`, `"GPT-5"`).
    pub model: Option<SharedString>,
    /// Optional muted inline detail after `name` (defaults to `model` when absent).
    pub detail: Option<SharedString>,
    /// Optional provider/tool icon key for [`pro_app_artwork`].
    pub icon: Option<SharedString>,
    /// Direct input tokens consumed by this span.
    pub tokens_in: u64,
    /// Direct output tokens generated by this span.
    pub tokens_out: u64,
    /// Direct USD cost of this span.
    pub cost: f64,
    /// Optional prompt or input preview shown in the span inspector.
    pub input: Option<SharedString>,
    /// Optional completion or tool output preview shown in the span inspector.
    pub output: Option<SharedString>,
    /// Optional error message shown when `status` is [`TraceSpanStatus::Failed`].
    pub error: Option<SharedString>,
    /// Nested child spans.
    pub children: Vec<TraceSpan>,
}

impl TraceSpan {
    /// Construct a new [`TraceSpan`] starting at `start_ms`.
    pub fn new(
        id: impl Into<SharedString>,
        name: impl Into<SharedString>,
        kind: TraceSpanKind,
        start_ms: u64,
    ) -> Self {
        Self {
            id: id.into(),
            name: name.into(),
            kind,
            status: TraceSpanStatus::Done,
            start_ms,
            end_ms: None,
            model: None,
            detail: None,
            icon: None,
            tokens_in: 0,
            tokens_out: 0,
            cost: 0.0,
            input: None,
            output: None,
            error: None,
            children: Vec::new(),
        }
    }

    /// Set the span execution status (`Running`, `Done`, `Failed`).
    pub fn with_status(mut self, status: TraceSpanStatus) -> Self {
        self.status = status;
        self
    }

    /// Set the completion timestamp in milliseconds from run start.
    pub fn with_end_ms(mut self, end_ms: u64) -> Self {
        self.end_ms = Some(end_ms);
        self
    }

    /// Set the model identifier and infer provider artwork.
    pub fn with_model(mut self, model: impl Into<SharedString>) -> Self {
        self.model = Some(model.into());
        self
    }

    /// Set the muted inline detail string shown beside `name`.
    pub fn with_detail(mut self, detail: impl Into<SharedString>) -> Self {
        self.detail = Some(detail.into());
        self
    }

    /// Set an explicit provider/tool icon key (`"claude"`, `"openai"`, `"stripe"`).
    pub fn with_icon(mut self, icon: impl Into<SharedString>) -> Self {
        self.icon = Some(icon.into());
        self
    }

    /// Set direct input and output token counts.
    pub fn with_tokens(mut self, tokens_in: u64, tokens_out: u64) -> Self {
        self.tokens_in = tokens_in;
        self.tokens_out = tokens_out;
        self
    }

    /// Set direct dollar cost.
    pub fn with_cost(mut self, cost: f64) -> Self {
        self.cost = cost;
        self
    }

    /// Set input/prompt and output/response previews for the span inspector.
    pub fn with_io(
        mut self,
        input: impl Into<SharedString>,
        output: impl Into<SharedString>,
    ) -> Self {
        self.input = Some(input.into());
        self.output = Some(output.into());
        self
    }

    /// Set only the input/task prompt (useful on root orchestrator spans).
    pub fn with_input(mut self, input: impl Into<SharedString>) -> Self {
        self.input = Some(input.into());
        self
    }

    /// Mark this span as [`TraceSpanStatus::Failed`] with an error description.
    pub fn with_error(mut self, error: impl Into<SharedString>) -> Self {
        self.status = TraceSpanStatus::Failed;
        self.error = Some(error.into());
        self
    }

    /// Attach nested child spans.
    pub fn with_children(mut self, children: Vec<TraceSpan>) -> Self {
        self.children = children;
        self
    }
}

/// Strongly typed events emitted by [`TraceWaterfall`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TraceWaterfallEvent {
    /// Emitted when opening or closing a span's inline inspector (`pro_fold`).
    OpenChanged(Option<SharedString>),
    /// Emitted when folding or unfolding a parent span branch.
    CollapsedChanged(Vec<SharedString>),
}

